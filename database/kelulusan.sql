CREATE DATABASE IF NOT EXISTS kelulusan CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE kelulusan;
SET NAMES utf8mb4;
SET time_zone = '+07:00';

DROP TABLE IF EXISTS log_akses, batas_coba, nilai, mapel, siswa, pengaturan, pengguna;

CREATE TABLE pengguna (
  id INT AUTO_INCREMENT PRIMARY KEY,
  nama VARCHAR(100) NOT NULL,
  username VARCHAR(40) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  role ENUM('admin','operator') NOT NULL DEFAULT 'operator',
  aktif TINYINT(1) NOT NULL DEFAULT 1,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE pengaturan (
  kunci VARCHAR(40) PRIMARY KEY,
  nilai TEXT
) ENGINE=InnoDB;

CREATE TABLE siswa (
  id INT AUTO_INCREMENT PRIMARY KEY,
  nisn VARCHAR(20) NOT NULL UNIQUE,
  nis VARCHAR(20) NOT NULL DEFAULT '',
  nama VARCHAR(120) NOT NULL,
  jk ENUM('L','P') NOT NULL DEFAULT 'L',
  kelas VARCHAR(30) NOT NULL,
  tempat_lahir VARCHAR(60) NOT NULL DEFAULT '',
  tgl_lahir DATE NOT NULL,
  nama_ortu VARCHAR(120) NOT NULL DEFAULT '',
  status ENUM('lulus','tidak_lulus','ditunda') NOT NULL DEFAULT 'lulus',
  catatan VARCHAR(255) NOT NULL DEFAULT '',
  no_urut INT NULL,                 -- nomor urut SKL (hanya siswa lulus)
  token CHAR(16) NOT NULL UNIQUE,   -- kode verifikasi di QR SKL
  dilihat_at DATETIME NULL,         -- pertama kali membuka pengumuman
  dilihat_kali INT NOT NULL DEFAULT 0,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX (kelas, nama)
) ENGINE=InnoDB;

CREATE TABLE mapel (
  id INT AUTO_INCREMENT PRIMARY KEY,
  kelompok VARCHAR(10) NOT NULL DEFAULT 'A',
  nama VARCHAR(100) NOT NULL,
  urutan INT NOT NULL DEFAULT 1
) ENGINE=InnoDB;

CREATE TABLE nilai (
  siswa_id INT NOT NULL,
  mapel_id INT NOT NULL,
  nilai DECIMAL(5,2) NOT NULL,
  PRIMARY KEY (siswa_id, mapel_id),
  FOREIGN KEY (siswa_id) REFERENCES siswa(id) ON DELETE CASCADE,
  FOREIGN KEY (mapel_id) REFERENCES mapel(id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- Setiap percobaan cek kelulusan (untuk statistik & audit)
CREATE TABLE log_akses (
  id INT AUTO_INCREMENT PRIMARY KEY,
  waktu DATETIME NOT NULL,
  siswa_id INT NULL,
  ip VARCHAR(45) NOT NULL,
  hasil ENUM('cocok','gagal','terkunci') NOT NULL,
  INDEX (waktu),
  FOREIGN KEY (siswa_id) REFERENCES siswa(id) ON DELETE SET NULL
) ENGINE=InnoDB;

-- Penghitung percobaan gagal per IP (anti tebak NISN + tanggal lahir)
CREATE TABLE batas_coba (
  kunci VARCHAR(80) PRIMARY KEY,
  n INT NOT NULL DEFAULT 0,
  mulai DATETIME NOT NULL
) ENGINE=InnoDB;


